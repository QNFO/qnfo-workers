#!/usr/bin/env python3
# AGENT-BOOTSTRAP-1: write (or check) the generated pointer block that makes every agent fetch the unified bootstrap.
# Usage: sync_agent_bootstrap.py [--check] FILE...   (after the first H1; replaces an existing block)
import sys
from pathlib import Path

URL = "https://raw.githubusercontent.com/QNFO/qnfo-workers/main/agent-bootstrap.md"
BEGIN, END = "<!-- AGENT-BOOTSTRAP-1:begin (generated by scripts/sync_agent_bootstrap.py; do not edit) -->", "<!-- AGENT-BOOTSTRAP-1:end -->"
BLOCK = f"""{BEGIN}
## Unified agent bootstrap (AGENT-BOOTSTRAP-1)
At the start of every session, fetch {URL} and follow it. It carries the current fleet-wide rules (self-closed loops, autonomy, closed loops) and wins over a stale local copy. If the fetch fails, continue with this file, record the failure as a loop item with a retry probe, and never ask a person. Put `bootstrap: <version>` in the PR body.
{END}"""


def upsert(text):
    if BEGIN in text and END in text:
        a, rest = text.split(BEGIN, 1)
        return a + BLOCK + rest.split(END, 1)[1]
    lines = text.split("\n")
    for i, l in enumerate(lines):
        if l.startswith("# "):
            return "\n".join(lines[: i + 1]) + "\n\n" + BLOCK + "\n" + "\n".join(lines[i + 1 :])
    return BLOCK + "\n\n" + text


def main():
    check = "--check" in sys.argv
    files = [a for a in sys.argv[1:] if not a.startswith("--")]
    bad = 0
    for f in files:
        p = Path(f)
        if not p.exists():
            print("missing", f); bad += 1; continue
        t = p.read_text(encoding="utf-8")
        n = upsert(t)
        if n != t:
            if check:
                print("DIFFERS", f); bad += 1
            else:
                p.write_text(n, encoding="utf-8"); print("wrote", f)
        else:
            print("same", f)
    sys.exit(1 if bad else 0)


main()
