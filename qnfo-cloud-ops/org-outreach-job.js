async function jobOrgOutreach(env) {
  const out = { mode: "off", candidates: 0, picked: 0, drafted: 0, sent: 0, skipped: {}, stop_synced: 0, replies: {}, capped: false, errors: [] };
  let cfg;
  try {
    const rows = (await env.AUDIT.prepare("SELECT key, value FROM ops_config WHERE key LIKE 'org_outreach_%'").all()).results || [];
    const g = (k) => { const r = rows.find((x) => x.key === k); return r ? String(r.value == null ? "" : r.value).trim() : ""; };
    cfg = { mode: g("org_outreach_mode") || ORG.DEFAULTS.mode, daily_cap: Number(g("org_outreach_daily_cap")) || ORG.DEFAULTS.daily_cap, postal_address: g("org_outreach_postal"), booking_url: g("org_outreach_booking_url") };
  } catch (e) {
    return { status: "error", reason: "ops_config unreadable: " + String(e && e.message || e).slice(0, 160), notes: out };
  }
  let sendsEnabled = false; // external_sends_enabled = "1" means external sends are allowed (the same reading as jobOutreach); anything else stops live sends
  try {
    const sw = await env.OUTREACH.prepare("SELECT value FROM pipeline_state WHERE key = 'external_sends_enabled'").first();
    sendsEnabled = !!(sw && sw.value === "1") && Date.now() >= OUTREACH_ACTIVATION_AT;
  } catch (e) {
    sendsEnabled = false; // an unreadable switch fails closed: the lane drafts
  }
  const mode = ORG.effectiveMode(cfg, sendsEnabled);
  out.mode = mode;
  await orgReplySync(env, out); // replies are read whatever the mode: a live send from an earlier run may have been answered
  if (mode === "off") return { status: "gated", notes: out };
  if (mode === "live" && !env.SEND_EMAIL) return { status: "error", notes: Object.assign(out, { errors: ["SEND_EMAIL binding missing"] }) };
  // STOP SYNC: an address that later landed on the suppression list closes its log row and its target (the learner counts it as a negative).
  try {
    const s = await env.AUDIT.prepare("UPDATE org_outreach_log SET reply_kind = 'stop', replied_at = datetime('now') WHERE reply_kind IS NULL AND lower(email) IN (SELECT lower(email) FROM email_suppression)").run();
    out.stop_synced = Number(s && s.meta && s.meta.changes || 0);
    await env.AUDIT.prepare("UPDATE org_targets SET status = 'stopped', updated_at = datetime('now') WHERE status IN ('queued','drafted') AND lower(email) IN (SELECT lower(email) FROM email_suppression)").run();
  } catch (e) {
    out.errors.push("stop sync: " + String(e && e.message || e).slice(0, 120));
  }
  const today = (/* @__PURE__ */ new Date()).toISOString().slice(0, 10);
  let targets, segRows, sentToday, shared;
  try {
    const statuses = mode === "live" ? "('queued','drafted')" : "('queued')";
    targets = (await env.AUDIT.prepare("SELECT id, org, email, segment, fit, fit_note, source_url FROM org_targets WHERE status IN " + statuses + " AND email IS NOT NULL AND email <> '' ORDER BY fit DESC LIMIT 50").all()).results || [];
    segRows = (await env.AUDIT.prepare("SELECT segment, sends, positive FROM v_org_outreach_segments").all()).results || [];
    sentToday = Number((await env.AUDIT.prepare("SELECT COUNT(*) AS n FROM org_outreach_log WHERE mode = 'live' AND sent_at LIKE ?1").bind(today + "%").first() || {}).n || 0);
    shared = await outreachSharedCount(env, today, "x@x.invalid");
  } catch (e) {
    return { status: "error", reason: "org lane unreadable: " + String(e && e.message || e).slice(0, 160), notes: out };
  }
  out.candidates = targets.length;
  const suppressed = /* @__PURE__ */ new Set(), contacted = /* @__PURE__ */ new Set();
  for (const t of targets) {
    const e = String(t.email || "").trim().toLowerCase();
    try { // fail closed: a read error stops the run, never waves an address through (OUTREACH-CONSENT-1)
      if (await outreachSuppressed(env, e)) suppressed.add(e);
      const dup = await env.AUDIT.prepare("SELECT 1 AS x FROM contact_ledger WHERE lower(email) = ?1 UNION ALL SELECT 1 AS x FROM outreach_log WHERE lower(email) = ?1 UNION ALL SELECT 1 AS x FROM org_outreach_log WHERE lower(email) = ?1 AND mode = 'live' LIMIT 1").bind(e).first();
      if (dup) contacted.add(e);
    } catch (err) {
      return { status: "error", reason: "consent lookup failed, nothing sent: " + String(err && err.message || err).slice(0, 160), notes: out };
    }
  }
  const batch = ORG.selectBatch(targets, { cfg, shared: { n: shared.n, cap: OUTREACH_SHARED_DAILY_CAP }, sentToday, segmentRows: segRows, choose: ORG_IL.chooseKnob, suppressed, contacted });
  out.picked = batch.picked.length;
  out.capped = batch.capped;
  for (const s of batch.skipped) for (const r of s.reasons) out.skipped[r] = (out.skipped[r] || 0) + 1;
  for (const p of batch.picked) {
    const t = p.target, email = String(t.email).trim().toLowerCase();
    try {
      const msg = ORG.buildMessage(t, cfg);
      if (mode === "live") {
        if (msg.blocked) { out.skipped[msg.blocked] = (out.skipped[msg.blocked] || 0) + 1; continue; }
        const sh = await outreachSharedCount(env, today, email);
        if (sh.n >= OUTREACH_SHARED_DAILY_CAP) { out.capped = true; break; }
        if (sh.d >= OUTREACH_SHARED_DOMAIN_CAP) { out.skipped["domain-cap"] = (out.skipped["domain-cap"] || 0) + 1; continue; }
        const res = await env.SEND_EMAIL.send({ to: email, from: OUTREACH_FROM, subject: msg.subject, text: msg.text });
        await env.AUDIT.prepare("INSERT INTO outreach_log (email, subject, message_id, sent_at, status) VALUES (?1,?2,?3, datetime('now'), 'sent')").bind(email, msg.subject, res && res.messageId || "").run();
        await env.AUDIT.prepare("INSERT INTO contact_ledger (email, name, first_contact, last_contact, contact_count, status) VALUES (?1,?2,?3,?3,1,'outreach') ON CONFLICT(email) DO UPDATE SET last_contact=excluded.last_contact, contact_count=contact_count+1").bind(email, t.org || null, today).run();
        await env.AUDIT.prepare("INSERT INTO org_outreach_log (target_id, email, segment, mode, subject, body, message_id) VALUES (?1,?2,?3,'live',?4,?5,?6)").bind(t.id, email, p.segment, msg.subject, msg.text, res && res.messageId || "").run();
        await env.AUDIT.prepare("UPDATE org_targets SET status = 'sent', updated_at = datetime('now') WHERE id = ?1").bind(t.id).run();
        await recordEvent(env, "outreach", "org-sent-" + Date.now().toString(36) + rndB36(4), "org outreach sent to " + email + " (" + p.segment + ")", outreachSendEvidence(email, res, "first", msg.subject, msg.text));
        out.sent++;
      } else {
        await env.AUDIT.prepare("INSERT INTO org_outreach_log (target_id, email, segment, mode, subject, body) VALUES (?1,?2,?3,'draft',?4,?5)").bind(t.id, email, p.segment, msg.subject, msg.text).run();
        await env.AUDIT.prepare("UPDATE org_targets SET status = 'drafted', updated_at = datetime('now') WHERE id = ?1").bind(t.id).run();
        out.drafted++;
      }
    } catch (e) {
      out.errors.push(String(t.id) + ": " + String(e && e.message || e).slice(0, 120));
    }
  }
  const status = out.errors.length && !out.sent && !out.drafted ? "error" : out.errors.length ? "partial" : "ok";
  return { status, notes: out };
}
