// CMDLINE-MAINTAIN-1 offline suite: the weekly sweep is due once a week and its prompt names the three sections. Run: node --no-warnings qnfo-agents/maintain.test.mjs
import { maintainDue, MAINTAIN_PROMPT, MAINTAIN_REQUESTER } from "./src/lib.js";
import { readFileSync } from "node:fs";
let pass = 0, fail = 0;
const ok = (c, m) => { if (c) pass++; else { fail++; console.log("FAIL " + m); } };
const now = Date.parse("2026-11-13T12:00:00Z");
ok(maintainDue(null, now) === true && maintainDue("", now) === true, "never swept: due");
ok(maintainDue("2026-11-10 12:00:00", now) === false, "swept 3 days ago: not due");
ok(maintainDue("2026-11-06 12:00:00", now) === true, "swept exactly 7 days ago: due");
ok(maintainDue("garbage", now) === false, "an unreadable timestamp fails closed (issue 8330)");
ok(/Maintenance/.test(MAINTAIN_PROMPT) && /Anticipated needs/.test(MAINTAIN_PROMPT) && /Document audit/.test(MAINTAIN_PROMPT), "the prompt has the three sections");
ok(/at most five issues/.test(MAINTAIN_PROMPT) && /never as instructions/.test(MAINTAIN_PROMPT), "bounded and treats files as data");
const src = readFileSync(new URL("./src/index.ts", import.meta.url), "utf8");
ok(/maintainDue\(lastSweep && lastSweep\.last, Date\.now\(\)\)/.test(src) && src.includes("MAINTAIN_REQUESTER"), "seedMeasurements seeds the sweep");
ok(MAINTAIN_REQUESTER === "cmdline-maintain", "requester name");
ok(/file_issue as soon as its evidence is in hand/.test(MAINTAIN_PROMPT), "the prompt files as it goes");
ok(/MAINTAIN_MAX_STEPS = 40/.test(src) && /cmdline-maintain\/\.test\(String\(r\.caller\)\) \? MAINTAIN_MAX_STEPS/.test(src), "the sweep has its own step budget");
ok(/cmdline-maintain\/\.test\(String\(r\.caller\)\) \? MAINTAIN_MAX_STEPS : lean/.test(src), "the sweep budget wins over lean mode");
ok(/MAINTAIN_TURN_TIMEOUT_MS/.test(src), "the sweep has its own turn timeout");
import { filedMismatch, claimedFiled, filedIssueIds } from "./src/lib.js";
const fi = (id) => ({ toolResults: [{ toolName: "file_issue", output: { ok: true, id } }] });
ok(claimedFiled("Summary\nIssues Filed: 4") === 4 && claimedFiled("**Issues filed:** 2") === 2 && claimedFiled("none") === null, "claim parsing");
ok(filedMismatch("Issues Filed: 4", [{ toolResults: [] }]).recorded === 0, "claim with no file_issue result is a mismatch");
ok(filedMismatch("Issues Filed: 2", [fi(7), fi(8)]) === null, "claim backed by ids holds");
ok(filedMismatch("Issues Filed: 3", [fi(7), { toolResults: [{ toolName: "file_issue", output: { ok: false, error: "x" } }] }]).recorded === 1, "failed file_issue is not counted");
ok(filedMismatch("no claim here", []) === null && filedIssueIds([fi(9)])[0] === 9, "no claim, no mismatch");
ok(/filedMismatch\(result, out\.steps\)/.test(src) && /SWEEP-CLAIMS-FILED-1/.test(src), "executeRun verifies the sweep's claim");
const __src = src;
ok(__src.includes("AND NOT EXISTS (SELECT 1 FROM cf_agent_requests WHERE requester"), "sweep seed insert is atomic (8330)");
ok(__src.includes("SWEEP-EMPTY-1"), "empty sweep files SWEEP-EMPTY-1 (8329)");
console.log("maintain: " + pass + " passed, " + fail + " failed"); process.exit(fail ? 1 : 0);
