// COMPANION-1 (personal-api/inline-companion.mjs): inlines personal-api/companion.js into personal-api/worker.js as the CMP namespace, between the
// COMPANION-INLINE-BEGIN / COMPANION-INLINE-END markers, and mirrors worker.js to deployed-current.worker.js.
// The canonical deploy uploads worker.js as ONE module (no relative imports), so edit companion.js and re-run:
//   node personal-api/inline-companion.mjs
import fs from "node:fs";
const dir = "personal-api/";
const src = fs.readFileSync(dir + "companion.js", "utf8");
const names = [];
const body = src.replace(/^export (async function|function|const|let|var|class) ([A-Za-z_$][\w$]*)/gm, (m, kw, id) => { names.push(id); return kw + " " + id; });
if (/^\s*(import|export)\b/m.test(body)) throw new Error("unhandled import/export in companion.js");
const block = "// COMPANION-INLINE-BEGIN (generated by personal-api/inline-companion.mjs from personal-api/companion.js; edit that file)\n" +
  "var CMP = (() => {\n" + body + "\nreturn Object.freeze({ " + names.join(", ") + " });\n})();\n// COMPANION-INLINE-END";
let worker = fs.readFileSync(dir + "worker.js", "utf8");
const re = /\/\/ COMPANION-INLINE-BEGIN[\s\S]*?\/\/ COMPANION-INLINE-END/;
if (!re.test(worker)) throw new Error("COMPANION-INLINE markers not found in worker.js");
worker = worker.replace(re, () => block);
fs.writeFileSync(dir + "worker.js", worker);
fs.writeFileSync(dir + "deployed-current.worker.js", worker);
console.log("ok", names.length, "exports,", worker.length, "bytes");
