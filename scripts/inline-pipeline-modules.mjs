#!/usr/bin/env node
// scripts/inline-pipeline-modules.mjs: PIPELINE-ENGINE-1. personal-companion deploys worker.js as ONE module (SINGLE-MODULE-INLINE-1),
// so the shared engine (_shared/pipeline-engine.js), the observed peers (_shared/pipeline-defs.js) and the personal pipeline
// (personal-companion/personal-pipeline.js) are inlined as namespaces PE, PD and PP between two markers. Re-runnable: it replaces the
// block in place (worker.js and its deployed-current mirror). personal-companion/personal-pipeline.test.mjs fails when the block is stale.
// Usage: node scripts/inline-pipeline-modules.mjs
import fs from "node:fs";
import { fileURLToPath } from "node:url";

export const BEGIN = "// ---- PIPELINE-ENGINE-INLINE:BEGIN (generated by scripts/inline-pipeline-modules.mjs; edit the source modules) ----";
export const END = "// ---- PIPELINE-ENGINE-INLINE:END ----";

function ns(name, text, file) {
  const names = [];
  let t = text.replace(/^import \* as (PE|PD|FR|PR) from "[^"]+";\s*$/gm, "");
  t = t.replace(/^export (async function|function|const|let|var|class) ([A-Za-z_$][\w$]*)/gm, (m, kw, id) => { names.push(id); return kw + " " + id; });
  if (/^\s*(import|export)\b/m.test(t)) throw new Error("unhandled import/export in " + file);
  return "var " + name + " = (() => {\n" + t + "\nreturn Object.freeze({ " + names.join(", ") + " });\n})(); // end inline " + file + "\n";
}

export function buildBlock(rootUrl) {
  const root = fileURLToPath(rootUrl);
  const rd = (p) => fs.readFileSync(root + p, "utf8");
  return BEGIN + "\n" + ns("PE", rd("_shared/pipeline-engine.js"), "_shared/pipeline-engine.js") + ns("PD", rd("_shared/pipeline-defs.js"), "_shared/pipeline-defs.js")
    + ns("PP", rd("personal-companion/personal-pipeline.js"), "personal-companion/personal-pipeline.js")
    + ns("FR", rd("_shared/flow-registry.js"), "_shared/flow-registry.js")
    + ns("PR", rd("_shared/product-research.js"), "_shared/product-research.js") + END;   // PRODUCT-RESEARCH-1
   //   // FLOW-DIRECTIVE-1
}

if (import.meta.url === "file://" + process.argv[1]) {
  const rootUrl = new URL("../", import.meta.url);
  const block = buildBlock(rootUrl);
  for (const f of ["personal-companion/worker.js", "personal-companion/deployed-current.worker.js"]) {
    const p = fileURLToPath(new URL(f, rootUrl));
    let w = fs.readFileSync(p, "utf8");
    const a = w.indexOf(BEGIN), b = w.indexOf(END);
    if (a < 0 || b < a) throw new Error(f + ": markers missing; add the BEGIN and END lines once, after the wellbeing inline block");
    w = w.slice(0, a) + block + w.slice(b + END.length);
    fs.writeFileSync(p, w);
    console.log("ok", f, w.length);
  }
}
