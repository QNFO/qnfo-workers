// CLAIM-ORDER-OWNER-1: class quotas replace strict tiers without starving proposals or aged rows.
// Run the shared selector and both claim paths from worker.js against SQLite.
// Run: node qnfo-research-exec/claim-order-owner.test.mjs   (exit 0 = all passed)
import { readFileSync } from "node:fs";
import { DatabaseSync } from "node:sqlite";
let pass = 0, fail = 0;
const ok = (c, m, x) => { if (c) pass++; else { fail++; console.log("FAIL " + m + (x !== undefined ? " :: " + JSON.stringify(x).slice(0, 300) : "")); } };
const src = readFileSync(new URL("./worker.js", import.meta.url), "utf8").replace(/\r\n/g, "\n");
const selector = src.match(/var RESEARCH_CLAIM_ID_SQL = `([^`]+)`;/)[1];
const claims = src.slice(src.indexOf("async function claimNew("), src.indexOf("__name(run,"));
ok((claims.match(/RESEARCH_CLAIM_ID_SQL/g) || []).length === 5, "atomic, fallback and legacy claims share the selector, including guarded fallback updates");
ok(!claims.includes("ORDER BY CASE WHEN source = 'proposal' AND attempt = 0"), "one-time proposal preference no longer imposes strict tiers");
ok(/status='researching' AND stage=\?1 ORDER BY CASE WHEN source='proposal' THEN 0 ELSE 1 END, claimed_at ASC LIMIT 1/.test(src), "the stage loop processes a researching proposal before a remediation row at the same stage");
const db = new DatabaseSync(":memory:");
db.exec("CREATE TABLE research_queue (id TEXT PRIMARY KEY, status TEXT, source TEXT, source_id TEXT, stage TEXT, created_at TEXT, score REAL, attempt INTEGER DEFAULT 0, claimed_at TEXT)");
const iso = (h) => new Date(Date.now() - h * 36e5).toISOString().slice(0, 19) + "Z";
const ins = db.prepare("INSERT INTO research_queue (id,status,source,source_id,stage,created_at,score) VALUES (?, 'queued', ?, ?, ?, ?, ?)");
ins.run("aged-old", "owner-corpus", "c1", null, iso(200), 0.2);
ins.run("aged-newer", "owner-corpus", "c2", null, iso(100), 0.9);
ins.run("fresh-generated", "radar", "r1", null, iso(2), 0.99);
ins.run("owner-idea", "idea", "i1", null, iso(1), 0.1);
ins.run("owner-chat-aged", "chat", "h1", null, iso(120), 0.1);
ins.run("resumed", "owner-corpus", "c3", "review", iso(5), 0.1);
ins.run("revision", "remediation", "revision:p1", null, iso(3), 0.1);
ins.run("proposal-aged", "proposal", "p1", null, iso(100), 0.4);
ins.run("proposal-fresh", "proposal", "p2", null, iso(1), 0.5);
const atomicParts = claims.match(/prepare\("([^"]+)" \+ RESEARCH_CLAIM_ID_SQL \+ "([^"]+)"\)\.bind\(nowIso\(\)\)/);
const atomic = db.prepare(atomicParts[1] + selector + atomicParts[2]);
const claim = () => atomic.get(new Date().toISOString());
let row = claim();
ok(row.id === "proposal-fresh" && row.attempt === 1 && row.stage === "ground", "a fresh high-score proposal gets the first claim, with atomic attempt and stage updates", row);
row = claim();
ok(row.id === "revision", "revision gets its class share without suppressing proposals", row);
row = claim();
ok(row.id === "fresh-generated", "other sources have a share too, ordered by score", row);
db.exec("UPDATE research_queue SET status='done'; UPDATE research_queue SET status='queued' WHERE id IN ('aged-old','aged-newer','fresh-generated','owner-idea','owner-chat-aged'); UPDATE research_queue SET attempt=0; UPDATE research_queue SET attempt=3 WHERE id='resumed'");
row = claim();
ok(row.id === "aged-old", "the fourth class turn takes the oldest aged row despite its lower score", row);
row = claim();
ok(row.id === "fresh-generated", "the next class turn returns to score order", row);
db.close();
console.log("claim-order-owner: " + pass + " passed, " + fail + " failed");
process.exit(fail ? 1 : 0);
