import assert from "node:assert/strict";
import { DatabaseSync } from "node:sqlite";
import { readFileSync } from "node:fs";
const sql = readFileSync(new URL("./2026-11-04-domain-managers.sql", import.meta.url), "utf8");
const m = sql.match(/'workflow', '(\{.*?\})', 60000/s);
const steps = JSON.parse(m[1].replace(/''/g, "'")).steps;
const db = new DatabaseSync(":memory:");
db.exec(`
CREATE TABLE management_personas (persona_key TEXT PRIMARY KEY, level TEXT NOT NULL, scope TEXT NOT NULL, charter TEXT, kpis TEXT, decision_authority TEXT, sla_min INTEGER, path_a TEXT, path_b TEXT, status TEXT DEFAULT 'active', updated_at TEXT);
CREATE TABLE persona_briefs (tick TEXT, persona_key TEXT, level TEXT, scope TEXT, verdict TEXT, decision TEXT, summary TEXT, computed_at TEXT, PRIMARY KEY (tick, persona_key));
CREATE TABLE persona_actions (id INTEGER PRIMARY KEY AUTOINCREMENT, ts TEXT DEFAULT CURRENT_TIMESTAMP, persona_key TEXT, kind TEXT, issue_id INTEGER, from_value TEXT, to_value TEXT, evidence TEXT, reverted_at TEXT);
CREATE TABLE agent_issues (id INTEGER PRIMARY KEY AUTOINCREMENT, title TEXT, description TEXT, source TEXT, category TEXT, priority TEXT, status TEXT, created_at INTEGER, updated_at INTEGER);
CREATE TABLE ops_config (key TEXT PRIMARY KEY, value TEXT, note TEXT, updated_at TEXT);
CREATE TABLE metric_registry (metric TEXT, last_value TEXT, last_refreshed TEXT, state TEXT);
CREATE TABLE product_registry (product TEXT PRIMARY KEY, host TEXT, what_for TEXT, plus_cadence_h INT, last_plus_at TEXT, rest_until TEXT, misses_in_row INT, state TEXT);
CREATE TABLE v_cost_run_rate (source_group TEXT, run_rate_30d_7d REAL);
CREATE TABLE v_channel_impact_7d (channel TEXT, posts_7d INT, human_clicks_7d INT, clicks_per_post_7d REAL);
CREATE TABLE outreach_log (id INTEGER PRIMARY KEY, sent_at TEXT, status TEXT);
INSERT INTO metric_registry VALUES ('domain_manager_briefs', NULL, NULL, NULL);
INSERT INTO product_registry VALUES ('jobs','jobs.q08.org','matcher',168,NULL,NULL,0,'active');
INSERT INTO v_cost_run_rate VALUES ('direct_providers_external:daily',450),('cloudflare_plan:daily',5),('total:x',455);
INSERT INTO v_channel_impact_7d VALUES ('bluesky',20,642,32.1),('linkedin',1,14,2.8);
`);
const run = () => { for (const s of steps) db.exec(s.sql); };
run(); run();
const titles = db.prepare("SELECT title FROM agent_issues ORDER BY id").all().map(r => r.title);
assert.ok(titles.some(t => t.startsWith("COST-MANAGER-1: direct_providers_external")));
assert.ok(titles.some(t => t.startsWith("SOCIAL-MANAGER-1: linkedin")));
assert.ok(titles.some(t => t.startsWith("SOCIAL-MANAGER-1: mastodon")));
assert.ok(titles.some(t => t.startsWith("OUTREACH-MANAGER-1")));
assert.ok(!titles.some(t => t.includes("bluesky")));
assert.equal(titles.length, 5, "second run files no duplicates");
assert.equal(db.prepare("SELECT COUNT(*) c FROM persona_briefs").get().c, 4);
assert.equal(db.prepare("SELECT COUNT(*) c FROM persona_actions").get().c, 5);
assert.equal(db.prepare("SELECT COUNT(*) c FROM management_personas").get().c, 4);
console.log("ok");
