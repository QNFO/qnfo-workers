#!/usr/bin/env python3
"""export_fleet_tasks_canonical.py - EXPORT-FLEET-TASKS-CANONICAL-1 (2026-10-19).

WHY
  docs/HANDOFF-2026-10-18.md §4.5 and §6.4: "docs/fleet-tasks-canonical.json is a dated snapshot and lags D1
  (fleet_tasks_canonical is the drift gate's source and IS in sync). No exporter script exists - that is the
  missing piece if the file is to stay honest."

  The file is read by humans and quoted in closeouts; the D1 table fleet_tasks_canonical is what the drift gate
  compares. Two copies of the same truth, one of them regenerated by hand, is how a snapshot starts lying. This
  script regenerates the file from the live table, in the file's existing shape, and can fail a check instead of
  writing when the two disagree.

WHAT IT READS
  qnfo-audit.fleet_tasks -> (id, version, enabled, updated_at, definition), ordered by id. `id` is the key the file
  already uses; `name` is a long description and is not a key.
  The output shape is the one the file already has, so a regeneration is a real diff or nothing:

    { "_comment": ..., "exported_at": <now>, "exported_by": "scripts/export_fleet_tasks_canonical.py",
      "tasks": { "<name>": { "version": n, "enabled": 0|1, "updated_at": "...", "definition": "<json text>" } } }

USAGE
  python3 scripts/export_fleet_tasks_canonical.py --check     # exit 1 when the file differs from D1 (CI gate)
  python3 scripts/export_fleet_tasks_canonical.py --write     # rewrite the file
  python3 scripts/export_fleet_tasks_canonical.py             # print the export to stdout

ENVIRONMENT
  CLOUDFLARE_API_TOKEN    token with D1 read
  CLOUDFLARE_ACCOUNT_ID   defaults to the fleet account

THE HONEST LIMIT
  Regenerating the file FROM live makes the file agree with live by construction, so it stops being an independent
  check - it becomes a readable, diffable mirror. That is the right trade only because the enforcing copy is
  qnfo-audit.fleet_tasks_canonical (which the drift gate compares against live), not this file. Run --check before
  --write when you want to SEE the drift; run --write to close it.
  `definition` is compared as a normalised JSON string: two documents that differ only in key order or whitespace are
  the same task. A semantic difference inside the JSON (a prompt word, a model id) is a difference here too, which is
  the point. A file that is behind D1 by only `exported_at` is not drift: that field is the export's own timestamp and
  is excluded from the comparison.
"""
import argparse
import json
import os
import sys
import urllib.error
import urllib.request

API = "https://api.cloudflare.com/client/v4"
ACCOUNT = os.environ.get("CLOUDFLARE_ACCOUNT_ID", "edb167b78c9fb901ea5bca3ce58ccc4b")
DB = "35e2e573-92f3-46ac-83c6-22f6429fc5e5"  # qnfo-audit
PATH = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "docs", "fleet-tasks-canonical.json")
NOTE = (
    "WORKFLOW-DEFINITION-DRIFT-1 (issue #1669). Canonical source of truth for live qnfo-audit fleet_tasks.definition "
    "values. The D1 table fleet_tasks_canonical is seeded from this file and a drift-gate fleet_task "
    "(fleet-tasks-drift-gate) files an agent_issue whenever the live definition differs from the canonical copy. "
    "Regenerate with scripts/export_fleet_tasks_canonical.py --write (never by hand)."
)


def d1(sql):
    token = os.environ.get("CLOUDFLARE_API_TOKEN")
    if not token:
        raise SystemExit("CLOUDFLARE_API_TOKEN is not set")
    body = json.dumps({"sql": sql}).encode()
    req = urllib.request.Request("%s/accounts/%s/d1/database/%s/query" % (API, ACCOUNT, DB), data=body, method="POST",
                                 headers={"Authorization": "Bearer " + token, "Content-Type": "application/json",
                                          "User-Agent": "qnfo-export-fleet-tasks/1.0 (+https://qnfo.org)"})
    try:
        with urllib.request.urlopen(req, timeout=60) as r:
            j = json.loads(r.read())
    except urllib.error.HTTPError as e:
        raise SystemExit("D1 HTTP %s: %s" % (e.code, e.read()[:300]))
    if not j.get("success"):
        raise SystemExit("D1 refused: " + json.dumps(j.get("errors"))[:300])
    res = j.get("result") or []
    return (res[0].get("results") if res else []) or []


def export():
    # `id` is the stable task key the file uses ("bench-arc-10task"); `name` is a long human sentence and is not
    # unique enough to key on. Measured 2026-10-19: keying on name made every task look new (23 file keys vs 36 D1
    # rows that shared no name with them).
    rows = d1("SELECT id, version, enabled, updated_at, definition FROM fleet_tasks ORDER BY id")
    tasks = {}
    for r in rows:
        tasks[r["id"]] = {
            "version": r.get("version"),
            "enabled": r.get("enabled"),
            "updated_at": r.get("updated_at"),
            "definition": r.get("definition"),
        }
    return {"_comment": NOTE, "exported_by": "scripts/export_fleet_tasks_canonical.py", "tasks": tasks}


def normalise(definition):
    """Compare JSON definitions structurally; fall back to the raw text when a definition is not JSON."""
    try:
        return json.dumps(json.loads(definition or "{}"), sort_keys=True, separators=(",", ":"))
    except Exception:  # noqa: BLE001
        return (definition or "").strip()


def diff(current, exported):
    """A list of human-readable differences between the file and D1, ignoring the export's own timestamp."""
    out = []
    a = (current or {}).get("tasks") or {}
    b = exported["tasks"]
    for name in sorted(set(a) | set(b)):
        if name not in a:
            out.append({"task": name, "change": "only in D1"})
        elif name not in b:
            out.append({"task": name, "change": "only in the file"})
        else:
            for field in ("version", "enabled", "updated_at"):
                if a[name].get(field) != b[name].get(field):
                    out.append({"task": name, "change": field, "file": a[name].get(field), "d1": b[name].get(field)})
            if normalise(a[name].get("definition")) != normalise(b[name].get("definition")):
                out.append({"task": name, "change": "definition"})
    return out


def main(argv=None):
    ap = argparse.ArgumentParser()
    g = ap.add_mutually_exclusive_group()
    g.add_argument("--check", action="store_true", help="exit 1 when the file differs from D1")
    g.add_argument("--write", action="store_true", help="rewrite docs/fleet-tasks-canonical.json")
    a = ap.parse_args(argv)
    exported = export()
    if a.check:
        try:
            with open(PATH, encoding="utf-8") as fh:
                current = json.load(fh)
        except FileNotFoundError:
            print(json.dumps({"ok": False, "error": "file missing", "path": PATH}))
            return 1
        d = diff(current, exported)
        print(json.dumps({"ok": not d, "tasks_in_file": len((current or {}).get("tasks") or {}),
                          "tasks_in_d1": len(exported["tasks"]), "differences": d}, indent=2)[:20000])
        return 0 if not d else 1
    if a.write:
        import datetime as dt
        exported["exported_at"] = dt.datetime.now(dt.timezone.utc).isoformat().replace("+00:00", "Z")
        with open(PATH, "w", encoding="utf-8", newline="\n") as fh:
            json.dump(exported, fh, indent=2, sort_keys=True)
            fh.write("\n")
        print(json.dumps({"ok": True, "written": PATH, "tasks": len(exported["tasks"]),
                          "exported_at": exported["exported_at"]}))
        return 0
    print(json.dumps(exported, indent=2, sort_keys=True)[:20000])
    return 0


if __name__ == "__main__":
    sys.exit(main())
