// TRAVEL-PLANNER-1: inline personal-companion/travel.js into personal-companion/worker.js as the namespace TRV, between the
// TRAVEL-INLINE-BEGIN and TRAVEL-INLINE-END markers (the deploy uploads worker.js as ONE module, no relative imports).
// Same transform as scripts/inline-companion-modules.mjs. Edit travel.js, then run:
//   node scripts/inline-companion-travel.mjs && cp personal-companion/worker.js personal-companion/deployed-current.worker.js
// personal-companion/travel.test.mjs fails when the block and travel.js disagree.
import fs from "node:fs";
const dir = "personal-companion/";
export function travelBlock(src) {
  const names = [];
  const t = src.replace(/^export (async function|function|const|let|var|class) ([A-Za-z_$][\w$]*)/gm, (m, kw, id) => { names.push(id); return kw + " " + id; });
  if (/^\s*(import|export)\b/m.test(t)) throw new Error("unhandled import/export in travel.js");
  return "// TRAVEL-INLINE-BEGIN (generated by scripts/inline-companion-travel.mjs from personal-companion/travel.js; do not edit here)\n" +
    "var TRV = (() => {\n" + t + "\nreturn Object.freeze({ " + names.join(", ") + " });\n})(); // TRAVEL-INLINE-END\n";
}
if (import.meta.url === "file://" + process.argv[1]) {
  let w = fs.readFileSync(dir + "worker.js", "utf8");
  const block = travelBlock(fs.readFileSync(dir + "travel.js", "utf8"));
  const re = /\/\/ TRAVEL-INLINE-BEGIN[^\n]*\n[\s\S]*?\/\/ TRAVEL-INLINE-END\n/;
  if (re.test(w)) w = w.replace(re, () => block);
  else {
    const anchor = "})(); // end inline wellbeing-wire.js\n";
    if (!w.includes(anchor)) throw new Error("wellbeing-wire anchor not found");
    w = w.replace(anchor, () => anchor + block);
  }
  fs.writeFileSync(dir + "worker.js", w);
  console.log("ok", w.length);
}
