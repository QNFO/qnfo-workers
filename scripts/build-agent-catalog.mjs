#!/usr/bin/env node
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

export const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const OUTPUTS = ["docs/INDEX.md", "docs/agent-catalog.json"];
export const ENTRYPOINTS = [
  "CLAUDE.md",
  "AGENTS.md",
  ".github/copilot-instructions.md",
  ".github/agents/quniverse.agent.md",
  "llms.txt",
  "docs/README.md",
  "docs/agent-library/README.md",
];
const HASHED = new Set(["llms.txt", "docs/README.md", "docs/agent-library/README.md"]);
const RAW = "https://raw.githubusercontent.com/QNFO/qnfo-workers/main/";

export function isSystemDocument(path) {
  if (OUTPUTS.includes(path)) return false;
  if (ENTRYPOINTS.includes(path) || /^\.github\/agents\/[^/]+\.md$/.test(path)) return true;
  if (!path.endsWith(".md") || path.startsWith(".")) return false;
  if (/^(archive|papers|funding)\//.test(path)) return false;
  return !/(^|\/)(node_modules|testdata|fixtures)(\/|$)/.test(path);
}

export function buildCatalog(root = ROOT) {
  const paths = execFileSync("git", ["ls-files", "-z"], { cwd: root, encoding: "utf8" })
    .split("\0").filter(isSystemDocument).sort();
  for (const path of ENTRYPOINTS) {
    if (!paths.includes(path)) throw new Error(`Missing tracked entry point: ${path}; stage new sources before generating`);
  }
  const documents = paths.map((path) => {
    const bytes = readFileSync(resolve(root, path));
    const title = bytes.toString("utf8").match(/^#\s+(.+)$/m)?.[1]?.trim() || path;
    return {
      path,
      title,
      url: RAW + path,
      ...(HASHED.has(path) ? { sha256: createHash("sha256").update(bytes).digest("hex") } : {}),
    };
  });
  const catalog = {
    schema_version: 1,
    contract: "FLEET-SHARED-LIBRARY-1",
    library_version: "1.0.0",
    repository: "QNFO/qnfo-workers",
    retrieval: "Resolve main to one commit; replace main in every URL with that commit. SHA-256 covers bootstrap/library bytes where present; other documents rely on the pinned Git revision.",
    authority: "Inventory is discovery, not adoption or proof of live state. Read CLAUDE.md and the charter/doctrine precedence rules.",
    entrypoints: ENTRYPOINTS,
    documents,
  };
  const lines = [
    "# System documentation index",
    "",
    "Generated by `node scripts/build-agent-catalog.mjs` from tracked system documents.",
    "Do not edit by hand. Inventory inclusion does not make a historical design current.",
    "",
    "Start with [the directory](README.md), [the shared library](agent-library/README.md),",
    "and [the machine-readable catalog](agent-catalog.json).",
    "",
  ];
  for (const [label, entries] of [
    ["Root and agent entry points", documents.filter(({ path }) => !path.includes("/") || path.startsWith(".github/"))],
    ["System standards, runbooks and historical records", documents.filter(({ path }) => path.startsWith("docs/"))],
    ["Component documentation", documents.filter(({ path }) => path.includes("/") && !path.startsWith("docs/") && !path.startsWith(".github/"))],
  ]) {
    lines.push(`## ${label}`, "");
    for (const { path, title } of entries) {
      const safeTitle = title.replace(/\\/g, "\\\\").replace(/[[\]]/g, "\\$&").replace(/\|/g, "\\|");
      const link = relative("docs", path).split("/").map(encodeURIComponent).join("/");
      lines.push(`- [${safeTitle}](${link}) - \`${path}\``);
    }
    lines.push("");
  }
  return new Map([
    ["docs/INDEX.md", lines.join("\n")],
    ["docs/agent-catalog.json", JSON.stringify(catalog, null, 2) + "\n"],
  ]);
}

export function checkCatalog(root = ROOT) {
  const stale = [];
  for (const [path, expected] of buildCatalog(root)) {
    let actual;
    try {
      actual = readFileSync(resolve(root, path), "utf8");
    } catch (error) {
      if (error.code !== "ENOENT") throw error;
    }
    if (actual !== expected) stale.push(path);
  }
  return stale;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  if (args.some((arg) => arg !== "--check") || args.length > 1) {
    throw new Error("Usage: node scripts/build-agent-catalog.mjs [--check]");
  }
  if (args.includes("--check")) {
    const stale = checkCatalog();
    if (stale.length) {
      console.error(`Stale documentation inventory: ${stale.join(", ")}. Run node scripts/build-agent-catalog.mjs`);
      process.exitCode = 1;
    } else {
      console.log("Agent documentation inventory is current");
    }
  } else {
    for (const [path, text] of buildCatalog()) writeFileSync(resolve(ROOT, path), text);
    console.log("Generated docs/INDEX.md and docs/agent-catalog.json");
  }
}
