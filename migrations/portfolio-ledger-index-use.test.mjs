// D1-LEDGER-SCAN-1: the portfolio-lifecycle dedupe probe names action = 'deployed', so the partial unique index serves it instead of a full scan per deploy.
import { readFileSync } from "node:fs";
import assert from "node:assert/strict";
import test from "node:test";
import { DatabaseSync } from "node:sqlite";

const file = readFileSync(new URL("./2026-11-14-portfolio-ledger-index-use.sql", import.meta.url), "utf8");
const snap = JSON.parse(readFileSync(new URL("../docs/fleet-tasks-canonical.json", import.meta.url), "utf8"));

function db(definition) {
  const d = new DatabaseSync(":memory:");
  d.exec(`CREATE TABLE fleet_tasks (id TEXT PRIMARY KEY, definition TEXT, version INTEGER, updated_at TEXT);
    CREATE TABLE fleet_tasks_canonical (id TEXT PRIMARY KEY, definition TEXT, repo_path TEXT, exported_at TEXT);
    CREATE TABLE project_ledger (id INTEGER PRIMARY KEY, project_id TEXT, session_id TEXT, phase INTEGER, task_id TEXT, action TEXT, evidence TEXT, worker_name TEXT, timestamp TEXT);
    CREATE UNIQUE INDEX ux_project_ledger_deploy ON project_ledger(task_id) WHERE action = 'deployed';
    CREATE TABLE deployment_history (id INTEGER PRIMARY KEY, resource_name TEXT, action TEXT, status TEXT, version_id TEXT, deployed_by TEXT, deployed_at TEXT);
    CREATE TABLE projects (project_code TEXT PRIMARY KEY);
    CREATE TABLE phases (project_code TEXT, phase_number INTEGER);`);
  d.prepare("INSERT INTO fleet_tasks VALUES ('portfolio-lifecycle', ?, 4, 'old')").run(definition);
  d.prepare("INSERT INTO fleet_tasks_canonical VALUES ('portfolio-lifecycle', ?, 'old', 'old')").run(definition);
  return d;
}
const firstStep = (def) => JSON.parse(def).steps.map((s) => s.sql).find((q) => q.startsWith("INSERT OR IGNORE INTO project_ledger") && q.includes("deployment_history dh"));
const OLD = "WHERE l.task_id='deploy:'||dh.id)";
const NEW = "WHERE l.task_id='deploy:'||dh.id AND l.action='deployed')";

test("the snapshot (dated export, regenerated by scripts/export_fleet_tasks_canonical.py) still holds the old step the migration rewrites", () => {
  assert.equal(snap.tasks["portfolio-lifecycle"].definition.split(OLD).length, 2);
});

test("the migration rewrites live and canonical alike, once, and the step uses the index", () => {
  const before = snap.tasks["portfolio-lifecycle"].definition;
  const d = db(before);
  const planOld = d.prepare("EXPLAIN QUERY PLAN " + firstStep(before).replace(/^INSERT OR IGNORE INTO project_ledger \([^)]*\) /, "")).all().map((r) => r.detail).join(" | ");
  assert.match(planOld, /SCAN l\b/);
  d.exec(file);
  d.exec(file);
  const live = d.prepare("SELECT definition, version FROM fleet_tasks").get();
  const canon = d.prepare("SELECT definition, repo_path FROM fleet_tasks_canonical").get();
  assert.equal(live.definition, canon.definition);
  assert.equal(live.version, 5);
  assert.equal(canon.repo_path, "migrations/2026-11-14-portfolio-ledger-index-use.sql");
  assert.equal(live.definition.split(NEW).length, 2);
  const planNew = d.prepare("EXPLAIN QUERY PLAN " + firstStep(live.definition).replace(/^INSERT OR IGNORE INTO project_ledger \([^)]*\) /, "")).all().map((r) => r.detail).join(" | ");
  assert.match(planNew, /USING COVERING INDEX ux_project_ledger_deploy/);
  assert.ok(!/SCAN l\b/.test(planNew));
});

test("the Rollback line restores the old text", () => {
  const before = snap.tasks["portfolio-lifecycle"].definition;
  const d = db(before);
  d.exec(file);
  d.exec(/^-- Rollback: (.*)$/m.exec(file)[1]);
  assert.equal(d.prepare("SELECT definition FROM fleet_tasks").get().definition, before);
  assert.equal(d.prepare("SELECT definition FROM fleet_tasks_canonical").get().definition, before);
});
