// IDEAS-CAP-PROBE-1 offline suite: replays migrations/2026-10-19-ideas-cap-release-probe.sql on SQLite.
// Proves: the closing contract of issue 100047 states its definition of done (room in the queue: no held cap row older than 120 minutes; full queue: a trickle run
// logged within 125 minutes while a row is held); it reads 0 for a draining full queue, 1 when the trickle stopped, the old room case still counts stale rows;
// a second apply changes nothing and keeps one decision_log row; the Rollback line restores the earlier probe and action byte for byte; LIKE literals are within 50 bytes.
// Run: node migrations/ideas-cap-release-probe.test.mjs
import { DatabaseSync } from "node:sqlite";
import { readFileSync } from "node:fs";
const sql = readFileSync(new URL("./2026-10-19-ideas-cap-release-probe.sql", import.meta.url), "utf8");
let pass = 0, fail = 0;
const ok = (c, m, d) => { if (c) pass++; else { fail++; console.log("FAIL " + m + (d === undefined ? "" : " :: " + JSON.stringify(d).slice(0, 300))); } };
const rollback = /^-- Rollback: (.+)$/m.exec(sql)[1];
const OLD_PROBE = rollback.match(/verify_probe = '((?:[^']|'')*)'/)[1].replace(/''/g, "'");
const OLD_ACTION = "VACUOUS-PROBE-V3-1: this contract measures nothing while the issue is open, so it is born superseded and never blocks the close. A doer that knows the defect replaces this probe with one that measures it.";
const d = new DatabaseSync(":memory:");
d.exec(`CREATE TABLE remediation_contracts (class TEXT PRIMARY KEY, issue_id INTEGER, action TEXT NOT NULL DEFAULT '', verify_probe TEXT, verify_transport TEXT, status TEXT, last_verdict TEXT, attempts INTEGER DEFAULT 0, deferred_since TEXT, next_due_at TEXT);
  CREATE TABLE decision_log (id INTEGER PRIMARY KEY AUTOINCREMENT, actor TEXT, assumption TEXT, action TEXT, evidence TEXT, outcome TEXT, blast_radius TEXT, rollback_path TEXT, capability_gain TEXT, predicted_outcome TEXT, reach_gain TEXT, surfaces_tested TEXT);
  CREATE TABLE idea_proposals (id INTEGER PRIMARY KEY, decision TEXT, status TEXT, rationale TEXT, created_at TEXT);
  CREATE TABLE research_queue (id TEXT PRIMARY KEY, status TEXT);
  CREATE TABLE cloud_ops_events (id TEXT PRIMARY KEY, ts TEXT, kind TEXT, job TEXT);`);
d.prepare("INSERT INTO remediation_contracts (class, issue_id, action, verify_probe, verify_transport, status, last_verdict, attempts) VALUES ('issue-100047', 100047, ?, ?, 'd1-query', 'active', 'fail', 7)").run(OLD_ACTION, OLD_PROBE);
d.prepare("INSERT INTO remediation_contracts (class, issue_id, action, verify_probe, verify_transport, status) VALUES ('issue-1', 1, 'keep', 'keep', 'd1-query', 'active')").run();
const get = () => d.prepare("SELECT * FROM remediation_contracts WHERE class = 'issue-100047'").get();
d.exec(sql);
const c = get();
ok(c.status === "active" && c.verify_transport === "d1-query" && c.last_verdict === null && c.attempts === 0 && /IDEAS-CAP-PROBE-1/.test(c.action), "the contract is restated, active, verdict cleared", c);
ok(!/agent_issues/.test(c.verify_probe), "the probe never reads the status of the issue itself");
ok(d.prepare("SELECT verify_probe FROM remediation_contracts WHERE class = 'issue-1'").get().verify_probe === "keep", "an unrelated contract is untouched");
const lits = [...c.verify_probe.matchAll(/LIKE '([^']*)'/g)].map((m) => Buffer.byteLength(m[1]));
ok(lits.length === 2 && lits.every((n) => n <= 50), "every LIKE literal is within 50 bytes", lits);
const iso = (min) => new Date(Date.now() - min * 60000).toISOString();
const held = d.prepare("INSERT INTO idea_proposals (id, decision, status, rationale, created_at) VALUES (?, ?, ?, ?, ?)");
const rq = d.prepare("INSERT INTO research_queue (id, status) VALUES (?, ?)");
const ev = d.prepare("INSERT INTO cloud_ops_events (id, ts, kind, job) VALUES (?, ?, ?, 'idea-hub')");
const probe = () => d.prepare(get().verify_probe).get();
for (let i = 0; i < 130; i++) rq.run("q" + i, i % 2 ? "queued" : "deferred");
held.run(1, "ACCEPT", "triaged_hold", "[research admission cap 130/120] idea", iso(3000));
held.run(2, "ACCEPT", "triaged_hold", "[research admission cap 130/120] idea", iso(10));
ok(probe().expected === "0" && probe().observed === "1", "a full queue with held rows and no trickle event reads 1 (the release is not running)", probe());
ev.run("e1", iso(30), "idea-cap-trickle");
ok(probe().observed === "0", "a full queue draining by the hourly trickle reads 0 although old rows are held", probe());
d.exec("DELETE FROM cloud_ops_events");
ev.run("e2", iso(200), "idea-cap-trickle");
ev.run("e3", iso(10), "idea-triage-budget");
ok(probe().observed === "1", "a trickle event older than 125 minutes, or another event kind, does not count", probe());
d.exec("DELETE FROM idea_proposals");
ok(probe().observed === "0", "a full queue with nothing held reads 0", probe());
d.exec("DELETE FROM research_queue WHERE rowid > 50");
held.run(3, "ACCEPT", "triaged_hold", "[research admission cap 130/120] idea", iso(10));
ok(probe().observed === "0", "room in the queue and the held row is younger than 120 minutes reads 0", probe());
held.run(4, "ACCEPT", "triaged_hold", "[research admission cap 130/120] idea", iso(300));
held.run(5, "ACCEPT", "triaged_hold", "[owner notebook] idea", iso(300));
held.run(6, "HOLD", "triaged_hold", "[research admission cap 130/120] idea", iso(300));
ok(probe().observed === "1", "room in the queue counts only ACCEPT cap rows older than 120 minutes", probe());
d.exec("UPDATE idea_proposals SET status = 'queued' WHERE id = 4");
ok(probe().observed === "0", "reads 0 once the stale row is released", probe());
d.exec(sql);
ok(d.prepare("SELECT COUNT(*) AS n FROM decision_log").get().n === 1 && get().attempts === 0, "a second apply changes nothing and keeps one decision_log row");
d.exec(rollback);
ok(get().verify_probe === OLD_PROBE && get().action === OLD_ACTION, "Rollback restores the earlier probe and action byte for byte");
console.log("ideas-cap-release-probe: " + pass + " passed, " + fail + " failed");
process.exit(fail ? 1 : 0);
