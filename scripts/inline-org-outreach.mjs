#!/usr/bin/env node
// scripts/inline-org-outreach.mjs: ORG-OUTREACH-1. qnfo-cloud-ops deploys worker.js as one module, so _shared/improve-loop.js (namespace ORG_IL, for chooseKnob),
// _shared/org-outreach.js (namespace ORG) and the executor qnfo-cloud-ops/org-outreach-job.js are spliced between two markers. Idempotent: the first run also adds the
// markers, the "org-outreach" job-map entry and its weekday schedule slot; later runs only regenerate the block. It writes worker.js, and the deployed-current mirror
// only when that mirror was byte-identical to worker.js before the run (otherwise it says so and leaves the mirror for mirror-guard.py).
// Usage: node scripts/inline-org-outreach.mjs   (then: python scripts/worker_release.py bump qnfo-cloud-ops --minor --note "ORG-OUTREACH-1 ...")
import fs from "node:fs";
import { fileURLToPath } from "node:url";

export const BEGIN = "// ---- ORG-OUTREACH-INLINE:BEGIN (generated by scripts/inline-org-outreach.mjs; edit _shared/org-outreach.js, _shared/improve-loop.js and qnfo-cloud-ops/org-outreach-job.js) ----";
export const END = "// ---- ORG-OUTREACH-INLINE:END ----";
const ANCHOR_JOB = '__name(jobOutreachLookup, "jobOutreachLookup");';
const ANCHOR_MAP = '  "outreach-lookup": jobOutreachLookup,';
const ANCHOR_SCHEDULE = '  "outreach": { times: ["11:00"], days: "1-5", fixed: null },';

function ns(name, text, file) {
  const names = [];
  const t = text.replace(/^export (async function|function|const|let|var|class) ([A-Za-z_$][\w$]*)/gm, (m, kw, id) => { names.push(id); return kw + " " + id; });
  if (/^\s*(import|export)\b/m.test(t)) throw new Error("unhandled import/export in " + file);
  return "var " + name + " = (() => {\n" + t + "\nreturn Object.freeze({ " + names.join(", ") + " });\n})(); // end inline " + file + "\n";
}

export function buildBlock(rootUrl) {
  const root = fileURLToPath(rootUrl);
  const rd = (p) => fs.readFileSync(root + p, "utf8");
  return BEGIN + "\n" + ns("ORG_IL", rd("_shared/improve-loop.js"), "_shared/improve-loop.js") + ns("ORG", rd("_shared/org-outreach.js"), "_shared/org-outreach.js")
    + rd("qnfo-cloud-ops/org-outreach-job.js") + END;
}

function once(text, anchor, insert, label) {
  const i = text.indexOf(anchor);
  if (i < 0 || text.indexOf(anchor, i + 1) >= 0) throw new Error("anchor for " + label + " must occur exactly once");
  return text.slice(0, i + anchor.length) + insert + text.slice(i + anchor.length);
}

export function apply(text, block) {
  let w = text;
  if (w.indexOf(BEGIN) < 0) {
    w = once(w, ANCHOR_JOB, "\n" + BEGIN + "\n" + END, "markers");
    w = once(w, ANCHOR_MAP, '\n  "org-outreach": jobOrgOutreach,', "job map");
    w = once(w, ANCHOR_SCHEDULE, '\n  // ORG-OUTREACH-1: organisation lane after the paper-author lane, so the shared 8/day cap serves that lane first; drafts unless ORG.effectiveMode says live.\n  "org-outreach": { times: ["15:05"], days: "1-5", fixed: null },', "schedule");
  }
  const a = w.indexOf(BEGIN), b = w.indexOf(END);
  if (a < 0 || b < a) throw new Error("markers missing");
  return w.slice(0, a) + block + w.slice(b + END.length);
}

if (import.meta.url === "file://" + process.argv[1]) {
  const rootUrl = new URL("../", import.meta.url);
  const block = buildBlock(rootUrl);
  const wp = fileURLToPath(new URL("qnfo-cloud-ops/worker.js", rootUrl));
  const mp = fileURLToPath(new URL("qnfo-cloud-ops/deployed-current.worker.js", rootUrl));
  const before = fs.readFileSync(wp, "utf8");
  const mirrorWasSame = fs.readFileSync(mp, "utf8") === before;
  const after = apply(before, block);
  fs.writeFileSync(wp, after);
  console.log("ok worker.js", after.length);
  if (mirrorWasSame) { fs.writeFileSync(mp, after); console.log("ok mirror copied"); } else console.log("mirror differs from worker.js before this run: build it with scripts/mirror-guard.py guidance");
}
