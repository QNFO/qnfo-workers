// scripts/product_tenant_scan.mjs: ULTRASTABLE-TENANT-1 (2026-11-12, charter pillar autonomy).
// WHAT   product/tenant.example.json names every setting the Ultrastable core reads and lists, per core worker (product/boundary.json class core),
//        each file and line where today's QNFO value is a constant. A later issue per worker replaces the constants with configuration.
// USAGE  node scripts/product_tenant_scan.mjs            # rewrite product/tenant.example.json from the tree
//        node scripts/product_tenant_scan.mjs --check    # exit 1 when a core worker file holds a constant the file does not list
import { readFileSync, writeFileSync, readdirSync, statSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

export const SETTINGS = {
  repository: { value: "QNFO/qnfo-workers", env: "TENANT_REPOSITORY", doc: "GitHub repository the issue mirror, code loop and deploy path work on" },
  workers_dev_host: { value: "q08.workers.dev", env: "TENANT_WORKERS_DEV_HOST", doc: "workers.dev subdomain of the account; every service-to-service URL" },
  dashboard_host: { value: "fleet.qnfo.org", env: "TENANT_DASHBOARD_HOST", doc: "operator console host" },
  account_id: { value: "edb167b78c9fb901ea5bca3ce58ccc4b", env: "TENANT_CF_ACCOUNT_ID", doc: "Cloudflare account that holds the workers, D1, KV and R2" },
  owner: { value: "rwnq8", env: "TENANT_OWNER", doc: "GitHub login of the owner and committer identity" },
};
const SKIP = (n) => /\.test\.|^deployed-current\.|^node_modules$|^releases$|^archive$/.test(n);
const EXT = /\.(js|mjs|ts|toml|json)$/;

function files(dir) {
  const out = [];
  for (const n of readdirSync(dir)) {
    if (SKIP(n)) continue;
    const p = join(dir, n);
    const st = statSync(p);
    if (st.isDirectory()) out.push(...files(p));
    else if (EXT.test(n) && st.size < 3_000_000) out.push(p);
  }
  return out;
}

export function scan(root, manifest) {
  const core = Object.entries(manifest.workers).filter(([, v]) => v.class === "core").map(([k]) => k).sort();
  const occurrences = {};
  for (const [key, s] of Object.entries(SETTINGS)) {
    occurrences[key] = {};
    for (const w of core) {
      const hits = [];
      for (const f of files(join(root, w))) {
        const lines = [];
        readFileSync(f, "utf8").split("\n").forEach((l, i) => { if (l.includes(s.value)) lines.push(i + 1); });
        if (lines.length) hits.push({ file: f.split("\\").join("/").slice(root.split("\\").join("/").length + 1), lines });
      }
      if (hits.length) occurrences[key][w] = hits;
    }
  }
  return occurrences;
}

export function build(root, manifest) {
  const occurrences = scan(root, manifest);
  const settings = {};
  for (const [k, s] of Object.entries(SETTINGS)) {
    const n = Object.values(occurrences[k]).flat().reduce((a, h) => a + h.lines.length, 0);
    settings[k] = { example: s.value, env: s.env, doc: s.doc, hardcoded_occurrences: n };
  }
  return { id: "ULTRASTABLE-TENANT-1", doc: "docs/PRODUCT-ULTRASTABLE.md", note: "Generated by scripts/product_tenant_scan.mjs. repository, hosts, account and owner are constants in the core workers today; settings names every value a tenant must supply and occurrences lists each place it is hardcoded (file and line numbers).", repository: SETTINGS.repository.value, settings, occurrences };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const root = join(dirname(fileURLToPath(import.meta.url)), "..");
  const manifest = JSON.parse(readFileSync(join(root, "product", "boundary.json"), "utf8"));
  const target = join(root, "product", "tenant.example.json");
  const fresh = build(root, manifest);
  if (process.argv.includes("--check")) {
    const have = JSON.parse(readFileSync(target, "utf8")).occurrences;
    const miss = [];
    for (const [k, byW] of Object.entries(fresh.occurrences)) for (const [w, hits] of Object.entries(byW)) for (const h of hits) if (!(have[k]?.[w] || []).some((x) => x.file === h.file)) miss.push(`${k}: ${h.file}`);
    for (const m of miss) console.log("UNLISTED " + m);
    process.exit(miss.length ? 1 : 0);
  }
  writeFileSync(target, JSON.stringify(fresh, null, 1) + "\n");
  console.log(JSON.stringify(Object.fromEntries(Object.entries(fresh.settings).map(([k, v]) => [k, v.hardcoded_occurrences]))));
}
