// UX-COVERAGE-MAP-1 (issue 8512): surface -> journey file, generated from the journey modules; coverage-map.md is its committed output.
// Run `node scripts/ux-journeys/coverage-map.mjs --write` after adding a surface; scripts/ux-journeys-coverage.test.mjs fails when it is stale.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
const dir = path.dirname(fileURLToPath(import.meta.url));
export async function buildMap() {
  const rows = [];
  const files = fs.readdirSync(path.join(dir, "apps")).filter((f) => f.endsWith(".journeys.mjs")).sort();
  for (const f of files) {
    const mod = await import(pathToFileURL(path.join(dir, "apps", f)).href);
    const src = fs.readFileSync(path.join(dir, "apps", f), "utf8");
    const hosts = new Set();
    if (Array.isArray(mod.HOSTS)) mod.HOSTS.forEach((h) => hosts.add(h[0]));
    if (mod.liveBase) hosts.add(new URL(mod.liveBase).hostname);
    for (const m of src.matchAll(/https:\/\/([a-z0-9.-]+\.(?:org|tech))(\/[A-Za-z0-9/_-]*)?/g)) hosts.add(m[1] + (m[2] && m[2] !== "/" ? m[2] : ""));
    hosts.forEach((h) => rows.push([h, "scripts/ux-journeys/apps/" + f, (mod.journeys || []).length]));
  }
  rows.sort((a, b) => a[0].localeCompare(b[0]) || a[1].localeCompare(b[1]));
  const lines = ["# UX journey coverage map (generated by scripts/ux-journeys/coverage-map.mjs; do not edit by hand)", "", "| surface | journey file | journeys |", "|---|---|---|"];
  rows.forEach((r) => lines.push("| " + r[0] + " | " + r[1] + " | " + r[2] + " |"));
  return lines.join("\n") + "\n";
}
if (process.argv[1] && pathToFileURL(path.resolve(process.argv[1])).href === import.meta.url) {
  const out = await buildMap();
  if (process.argv.includes("--write")) fs.writeFileSync(path.join(dir, "coverage-map.md"), out); else process.stdout.write(out);
}
