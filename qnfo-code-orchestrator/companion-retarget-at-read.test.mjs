// ct_iui23eipw5w1lh, ct_yb3aomxnk3to5u and ct_rih48qvd8s1bo9 were filed on personal-api/worker.js with an anchor inside the generated COMPANION-INLINE region and each failed the
// parity suite "worker.js carries the current companion.js" (the region is copied byte for byte from personal-api/companion.js by personal-api/inline-companion.mjs). The planner
// path (#6314) and the fail-time retarget (COMPANION-RETARGET-1, #7029) knew it; a task written by a retry, the RED-DRAIN dispatch or a direct enqueue still spent a failed attempt
// first (ct_u9huz7zbg8aahu). This suite proves the read step retargets such a row up front, with no model call, and leaves every other row alone:
//   1. anchor inside the inline region of personal-api/worker.js -> path personal-api/companion.js, goal gains the regenerate instruction, anchor kept, step read -> propose;
//   2. anchor outside the region (worker.js own code) -> path stays personal-api/worker.js;
//   3. a goal that already says "Edit personal-api/companion.js as the source" is not retargeted twice;
//   4. an anchor that companion.js does not hold exactly once -> stays on worker.js (nothing is guessed);
//   5. another worker's file with the same anchor text is never retargeted.
// Run: node qnfo-code-orchestrator/companion-retarget-at-read.test.mjs   -> prints "N passed, 0 failed"
